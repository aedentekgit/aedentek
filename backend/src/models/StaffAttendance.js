import mongoose from 'mongoose';

const staffAttendanceSchema = new mongoose.Schema({
  staffRef: { type: mongoose.Schema.Types.ObjectId, ref: 'Staff', default: null, index: true },
  staffId: { type: String, default: '', index: true },
  staffName: { type: String, default: '' },
  role: { type: String, default: '' },
  branch: { type: String, default: '', index: true },
  date: { type: String, required: true, index: true },

  checkIn: { type: String, default: '' },
  checkOut: { type: String, default: '' },
  workingHours: { type: String, default: '' },

  status: {
    type: String,
    enum: ['Present', 'Late', 'Absent', 'Half Day', 'On Leave'],
    default: 'Present',
    index: true
  },
  lateMinutes: { type: Number, default: 0, min: 0 },
  lateFine: { type: Number, default: 0, min: 0 },

  deviceId: { type: String, default: '' },
  remarks: { type: String, default: '' },
  // Rows generated by approving a leave request — removed again if that leave is rejected/deleted.
  isSynthetic: { type: Boolean, default: false, index: true }
}, { timestamps: true });

export default mongoose.model('StaffAttendance', staffAttendanceSchema);
